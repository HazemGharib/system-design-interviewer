export interface CheatEntry {
  id: string;
  problem: { ar: string; en: string };
  patterns: { ar: string; en: string };
  when: { ar: string; en: string };
  tradeoffs: { ar: string; en: string };
  example: { ar: string; en: string };
  tags: string[];
}

export interface CheatCategory {
  id: string;
  title: { ar: string; en: string };
  entries: CheatEntry[];
}

export interface NumbersSection {
  title: { ar: string; en: string };
  items: { label: { ar: string; en: string }; value: { ar: string; en: string } }[];
}

function e(
  id: string,
  problem: [string, string],
  patterns: [string, string],
  when: [string, string],
  tradeoffs: [string, string],
  example: [string, string],
  tags: string[]
): CheatEntry {
  return {
    id,
    problem: { ar: problem[0], en: problem[1] },
    patterns: { ar: patterns[0], en: patterns[1] },
    when: { ar: when[0], en: when[1] },
    tradeoffs: { ar: tradeoffs[0], en: tradeoffs[1] },
    example: { ar: example[0], en: example[1] },
    tags,
  };
}

